/**
 * 拼出完整的缓存段：系统常量 + 命令目录 + 门店档案。
 *
 * ⚠️ 顺序不许改。最稳定的在最前面（常量 → 目录 → 档案），
 * 这样店主改了一个服务项目时，前面两段的缓存仍然命中。
 */
export function copilotSystemText(
  commandCatalog: string,
  storeProfileText?: string,
): string {
  const base = `${COPILOT_SYSTEM}\n\n${commandCatalog}\n`;
  return storeProfileText ? `${base}\n${storeProfileText}\n` : base;
}

/**
 * 用户那一轮的文本。**这一段每次都不一样，不进缓存**。
 *
 * 顺序有讲究：时间锚点在最前、现场快照次之、预约日历再次、问题最后。
 * 模型读到问题时，时间基准与全部业务上下文已经在手上了。
 */
export function copilotUserText(args: {
  timeAnchor?: TimeAnchor | string | undefined;
  snapshot?: string | undefined;
  calendar?: string | undefined;
  question: string;
}): string {
  const blocks: string[] = [];

  if (args.timeAnchor) {
    blocks.push(
      typeof args.timeAnchor === 'string' ? args.timeAnchor : formatTimeAnchor(args.timeAnchor),
    );
  }
  if (args.snapshot) {
    blocks.push(`<现场快照>\n${args.snapshot}\n</现场快照>`);
  }
  if (args.calendar) {
    blocks.push(args.calendar);
  }
  blocks.push(`前台说：${args.question}`);

  return blocks.join('\n\n');
}
