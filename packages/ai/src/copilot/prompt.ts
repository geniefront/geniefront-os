/**
 * 前台副驾的提示词组装（05 §6.2）
 *
 * ## 两段式结构
 *
 * ```
 * [ instructions · 逐字节稳定 · 命中 OpenAI 前缀缓存，0.1 倍计价 ]
 *   ├── COPILOT_SYSTEM（这段常量，永不掺入任何门店数据）
 *   ├── 命令目录（按权限集合生成，少量稳定变体）
 *   └── 门店档案（服务/员工/房间/营业时间 —— 只在店主改配置时才变）
 * [ user turn · 每轮重建 ]
 *   ├── 权威时间锚点
 *   ├── 现场快照（轮牌 / 在做 / 队列）
 *   ├── 预约日历（过去 7 天 ~ 未来 30 天）
 *   └── 前台本次输入
 * ```
 *
 * ⚠️ **门店档案放进 instructions 是故意的。** 这和 Anthropic 那套显式
 * 缓存断点的直觉相反：OpenAI 是自动前缀匹配，每家门店命中自己那一份
 * 变体，同一个前台连续提问全部命中；放进 user turn 反而永远命中不了。
 * 但 `COPILOT_SYSTEM` 这段常量本身仍然不许掺任何变量 —— 它在最前面，
 * 变一个字节，后面全部失效。
 *
 * 验证方法：看 `usage.cachedInputTokens`，一直是 0 就说明有东西在偷偷
 * 让缓存失效。
 */

