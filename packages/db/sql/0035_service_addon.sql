--  0035 · 项目表上的「这是加项」标记位
--
--  ## 要解决的问题
--
--  加项（Add-on）在这个数据模型里就是一条普通的 services 行 ——
--  `appointment_items.addon_ids` 引用的正是它们，没有单独的「加项目录」。
--  这个设计本身没问题（价格、时长、提成都能复用），但它丢掉了一件事：
--  **一条 services 行是不是只能加在别的项目上**。
--
--  这件事在电话上会出人命（docs/14 §2 的第二个已知限制）：
--
--      客人：「热石多少钱？」
--      AI  ：「热石十五块。」          ← list_services 里它长得和别的项目一样
--      客人：（到店）「我做十五块的热石。」
--      前台：「热石是加在按摩上的，单做没有这一项。」
--
--  拍价目表那条路上，模型**本来就判断得出**（blueprint_items.kind = 'addon'，
--  05 §5.3），只是一直没有地方存 —— 建成 services 行的时候那个 kind 被丢掉了。
--
--  ## 为什么是布尔列而不是新的一张表
--
--  加项和项目共用的东西太多：价格、时长、税、提成、名字多语言。
--  拆表要把这些全复制一份，而两份实现迟早会不一致（改了项目的提成规则，
--  加项的没跟上）。一个布尔列表达的就是它真实的样子：
--  **一条卖得出去的项目，只是不能单独卖**。
--
--  默认 false：已有的项目全都保持「主项目」，没有一条会因为这次迁移
--  从官网或电话里消失。老板在门店设置里逐个勾。
-- ════════════════════════════════════════════════════════════════════════════

alter table services
  add column if not exists is_addon boolean not null default false;

comment on column services.is_addon is
  '加项：只能加在主项目上，不能单独预约。电话 AI 与官网预约页按它分开展示';

-- 电话 AI 每通电话都要按 is_addon 把目录分成两半，而项目表是按门店查的
create index if not exists services_addon_idx
  on services (location_id, is_addon) where active;
