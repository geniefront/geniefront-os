--  0036 · 电话工具的第二把钥匙（每条 AI 线一串不可猜的 token）
--
--  ## 它解决什么
--
--  六个电话工具的身份证明只有一个 Ed25519 签名（0015、docs/14 §0）。
--  门店靠**被叫号码**定位，而号码是店家印在门口和 Google 上的公开信息。
--  也就是说：**一旦验签这道门被绕过，攻击者可以逐个号码点名查任意一家店**
--  —— 客户名字、上次做的项目、价目表、谁在班，还能建单。
--
--  这一列是那道门后面的第二道：每条 `ai_voice` 线一串 32 字节随机 token，
--  填进 Telnyx 那家店的 assistant 配置里，每次工具调用随请求体带回来。
--  验签通过之后再比一次，对不上一律 401。
--
--  ## ⚠️ 它买不到什么（别高估）
--
--  · **不是门店 id，也不能替代号码。** `call.hangup` / `message.received`
--    这些 webhook 不是 assistant 的工具调用，带不了自定义参数 ——
--    那条路上唯一能确定租户的仍然只有被叫号码。
--  · **挡不住 Telnyx 账号被拿下。** 签名公钥和这串 token 都在那个后台里，
--    进得去的人两样都拿得到。它只在「我们自己的验签代码有洞」时起作用。
--  · **多一样要人工同步的东西。** 忘了填进 assistant 配置，那家店的电话
--    当场全 401（日志里 reason 是 shop_token_invalid）。
--
--  ## 为什么只存摘要
--
--  和管理令牌、上机码、设备令牌同一个套路：明文只在生成它的那次命令的
--  返回里出现一次，库里从此只有 SHA-256。**库被复制走也换不来一次调用。**
--  代价是丢了只能轮换 —— 而轮换本来就该是随时能做的事。
--
--  默认 NULL = 这条线还没有 token，**照旧只验签名**。存量号码不会因为
--  这次迁移在半夜里停掉。
-- ════════════════════════════════════════════════════════════════════════════

alter table phone_lines
  add column if not exists tool_token_digest text;

comment on column phone_lines.tool_token_digest is
  '电话工具 token 的 SHA-256 摘要。非空则每次工具调用必须带上匹配的 shop_token；明文只在生成时返回一次';
